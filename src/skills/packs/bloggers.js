const WORD_END = '(?![а-яё])'; // \b в JS не работает с кириллицей

// Текст стиля из структурированного пресета: роль → лексика → синтаксис.
// Пресет можно расширять данными, не трогая промпт.
function presetStyleText(preset) {
  return [
    preset.role,
    preset.lexicon ? `Лексика: ${preset.lexicon}` : '',
    preset.syntax ? `Синтаксис: ${preset.syntax}` : '',
    preset.composition ? `Композиция и оптика: ${preset.composition}` : '',
    preset.rhythm ? `Ритм (если пишешь стихи): ${preset.rhythm}` : '',
    preset.intonation ? `Интонация и жанры: ${preset.intonation}` : '',
    preset.forbidden ? `Запреты (негативный промпт): ${preset.forbidden}` : '',
    Array.isArray(preset.tasks) && preset.tasks.length > 0
      ? `Задачи (подстрой под текст, если он соответствует):\n${preset.tasks.map((task) => `— ${task.when}: ${task.instruction}`).join('\n')}\nЕсли текст не подходит ни под одну задачу — выбери уместный регистр из «Интонации и жанры».`
      : '',
    preset.instruction
  ].filter(Boolean).join('\n\n');
}

