/**
 * Возвращает персону по id. Неизвестный/пустой id → персонаж по умолчанию.
 * @param {string} [personaId]
 */
function getPersona(personaId) {
  const id = (personaId || '').trim() || 'hedgehog';
  const persona = personas[id];

  if (!persona) {
    // Незнакомое значение не роняем бот, а откатываемся к ежику.
    return personas.hedgehog;
  }

  return persona;
}

