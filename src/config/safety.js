// Правила безопасности и тексты отказов — единый источник для промптов
// (персона, скиллы) и для модуля цензуры (src/core/moderation.js).
//
// Здесь только формулировки. Сама проверка входа и распознавание отказов
// модели живут в src/core/moderation.js.

const HELPLINE = '8-800-2000-122';

// Вставляется в системный промпт персонажа и в каждый промпт скилла.
// Неоднозначные глаголы («убить», «взорвать») специально оставляем модели:
// по контексту она отличает «убить время» от «убить человека».
const SAFETY_RULES = [
  'Правила безопасности (обязательны): не создавай, не описывай и не обсуждай контент о насилии и жестокости, терроризме и экстремизме, изготовлении оружия, взрывчатки или наркотиков, суициде и самоповреждении, порнографии.',
  'Если просьба касается этих тем — вежливо откажись одной фразой и предложи безопасную альтернативу по теме текста.',
  'Неоднозначные слова оценивай по контексту: «убить время», «убить процесс», «взорвать рынок» — безопасные метафоры, их можно использовать.'
].join('\n');

const GENERAL_REFUSAL_TEXT = 'Не смогу помочь с этой темой: я не создаю контент о насилии, терроризме, наркотиках, оружии и материалах 18+. Давайте выберем безопасную тему — например, текст о вашем продукте, событии или идее.';

const SUICIDE_REFUSAL_TEXT = `Мне жаль, что вам сейчас тяжело. Я не могу помогать с темами о причинении вреда себе, но рядом есть люди, готовые поддержать: телефон доверия ${HELPLINE} (бесплатно, круглосуточно). Если есть возможность, поговорите с близким человеком или специалистом.`;

// Оборачивает prompt скилла: правила безопасности идут первыми, чтобы
// модель видела их до пользовательского текста.
function withSafetyRules(prompt) {
  return (...args) => `${SAFETY_RULES}\n\n${prompt(...args)}`;
}

module.exports = {
  HELPLINE,
  SAFETY_RULES,
  GENERAL_REFUSAL_TEXT,
  SUICIDE_REFUSAL_TEXT,
  withSafetyRules
};
